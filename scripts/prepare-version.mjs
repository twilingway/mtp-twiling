import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));

async function inputs(directory) {
  const files = [];
  for (const item of await readdir(directory, { withFileTypes: true })) {
    const file = join(directory, item.name);
    if (item.isDirectory()) {
      // Generated licenses first appear after a clean build and must not change its ID.
      if (!["vendor", "assets", "generated", "licenses"].includes(item.name))
        files.push(...(await inputs(file)));
    } else files.push(file);
  }
  return files;
}

export async function prepareVersion(projectRoot = root) {
  const version = JSON.parse(await readFile(join(projectRoot, "package.json"), "utf8")).version;
  const source = [
    ...(await inputs(join(projectRoot, "src"))),
    ...(await inputs(join(projectRoot, "public")))
  ]
    .filter((file) => !file.endsWith(".js") && !file.endsWith("version.json"))
    .map((file) => relative(projectRoot, file).replaceAll("\\", "/"))
    .sort();
  const hash = createHash("sha256");
  for (const file of source) {
    hash.update(file);
    hash.update(await readFile(join(projectRoot, file)));
  }
  for (const file of [
    "package.json",
    "pnpm-lock.yaml",
    "scripts/build.mjs",
    "scripts/prepare-version.mjs",
    "scripts/service-worker.template.js",
    "server.mjs",
    "deploy/static/nginx.conf",
    "tsconfig.json"
  ]) {
    hash.update(file);
    hash.update(await readFile(join(projectRoot, file)));
  }
  const buildId = hash.digest("hex").slice(0, 16);
  await mkdir(join(projectRoot, "src/generated"), { recursive: true });
  await writeFile(
    join(projectRoot, "src/generated/app-version.ts"),
    `// Generated by scripts/prepare-version.mjs.\nexport const APP_VERSION = ${JSON.stringify(version)};\nexport const BUILD_ID = ${JSON.stringify(buildId)};\n`
  );
  return { version, buildId };
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href)
  await prepareVersion();
