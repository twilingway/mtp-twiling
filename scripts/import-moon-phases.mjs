import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";

const sourceUrl = "https://www.astropixels.com/ephemeris/moon/phases2001gmt.html";
const credit = "Moon Phases Table courtesy of Fred Espenak, www.Astropixels.com";
const [input] = process.argv.slice(2);
assert.ok(input, "Pass the downloaded AstroPixels GMT HTML file");
const html = readFileSync(input, "utf8");
assert.ok(html.includes(credit), "Expected AstroPixels data with reproduction credit");
const months = "Jan Feb Mar Apr May Jun Jul Aug Sep Oct Nov Dec".split(" ");
const yearPhases = new Map();
for (const [, table] of html.matchAll(/<pre>([\s\S]*?)<\/pre>/g)) {
  if (!table.includes("First Quarter") || !table.includes("Full Moon")) continue;
  let year;
  for (const line of table.split(/\r?\n/)) {
    const nextYear = /^ (\d{4})\s/.exec(line)?.[1];
    if (nextYear) {
      year = Number(nextYear);
      assert.ok(year >= 2001 && year <= 2100 && !yearPhases.has(year));
      yearPhases.set(year, []);
    }
    if (!year || !/^ (?:\d{4}| {4}) /.test(line)) continue;
    for (const [kind, column] of [
      ["N", 10],
      ["F", 46]
    ]) {
      const field = line.slice(column, column + 18).trim();
      if (!field) continue;
      const entry = /^([A-Z][a-z]{2})\s+(\d{1,2})\s+(\d{2}):(\d{2})(?: [A-Za-z])?$/.exec(field);
      assert.ok(entry, `Invalid source datum in ${year}: ${field}`);
      const [, month, day, hour, minute] = entry;
      const monthNumber = months.indexOf(month) + 1;
      const timestamp = Date.UTC(year, monthNumber - 1, Number(day), Number(hour), Number(minute));
      assert.ok(monthNumber > 0 && new Date(timestamp).getUTCDate() === Number(day));
      yearPhases.get(year).push({ kind, timestamp });
    }
  }
}

assert.equal(yearPhases.size, 100);
const records = [];
let previous;
for (const [year, entries] of yearPhases) {
  assert.equal(year, 2001 + records.length);
  assert.ok(entries.length >= 23 && entries.length <= 26);
  entries.sort((a, b) => a.timestamp - b.timestamp);
  const phases = entries.map(({ kind, timestamp }) => {
    if (previous) {
      assert.notEqual(kind, previous.kind, "Lunar phases should alternate");
      const elapsedDays = (timestamp - previous.timestamp) / 86400000;
      assert.ok(elapsedDays > 12 && elapsedDays < 17, "Check source for missing events");
    }
    previous = { kind, timestamp };
    const compact = new Date(timestamp).toISOString().slice(5, 16).replaceAll(/[-T:]/g, "");
    return `${kind}${compact}`;
  });
  records.push(`  [${year}, "${phases.join(" ")}"]`);
}

const code = `// Generated by scripts/import-moon-phases.mjs. Entries are N/F followed by MMDDHHmm in UT.
// ${credit}
// ${sourceUrl}
export const moonPhaseYears: readonly (readonly [number, string])[] = [
${records.join(",\n")}
];
`;
writeFileSync(
  new URL(
    "../src/model/technical-indicators/catalog-expansion/moon-phase-years.ts",
    import.meta.url
  ),
  code,
  "utf8"
);
